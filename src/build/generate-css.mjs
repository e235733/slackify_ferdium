// Evaluates the pinned Slackify config/themes/styles in an isolated VM context and writes
// dist/user.css plus the selector/tag metadata consumed by the runtime.
import vm from 'node:vm';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

export function loadUpstream() {
  const sandbox = {};
  sandbox.globalThis = sandbox;
  const ctx = vm.createContext(sandbox, { codeGeneration: { strings: false, wasm: false } });
  for (const f of ['config', 'themes', 'styles']) {
    vm.runInContext(read(`src/upstream/${f}.js`), ctx, { filename: `${f}.js`, timeout: 5000 });
  }
  return sandbox;
}

function fontFaceCSS() {
  return [400, 700, 900].map((w) => {
    const b64 = fs.readFileSync(path.join(root, `src/upstream/fonts/lato-${w}.woff2`)).toString('base64');
    return `@font-face{font-family:'SlackifyLato';font-style:normal;font-weight:${w};font-display:swap;` +
      `src:url('data:font/woff2;base64,${b64}') format('woff2');}`;
  }).join('\n');
}

export function build() {
  const up = loadUpstream();
  const upstreamCss = up.SLACKIFY_STYLES.buildCSS();
  const compat = read('src/css/compat.css');
  const banner = '/* Generated by ferdium-gchat-slackify from gchat-slackify (MIT). Do not edit. */\n' +
    '/* Lato: SIL Open Font License 1.1, (c) 2010-2011 tyPoland Lukasz Dziedzic. */\n';
  const raw = `${banner}${fontFaceCSS()}\n${upstreamCss}\n/* --- Ferdium compat --- */\n${compat}\n`;
  // Policy: no external URLs. Upstream swaps the Chat logo (img[src*="chatlogo"], same scoping: dark top-bar
  // themes only) for a gstatic image; keep that exact scope but make the native logo white via a CSS filter.
  const ast = postcss.parse(raw); // throws on syntax errors
  ast.walkRules((r) => {
    if (!/ssl\.gstatic\.com/.test(r.toString())) return;
    r.removeAll();
    r.append({ prop: 'filter', value: 'brightness(0) invert(1)', important: true });
  });
  const css = ast.toString();
  const { SELECTORS, TAGS, FEATURES, DEFAULT_PREFS } = up.SLACKIFY_CONFIG;
  const meta = {
    upstreamVersion: '1.4.4',
    SELECTORS, TAGS,
    FEATURES: FEATURES.map((f) => ({ id: f.id, default: f.default })),
    theme: DEFAULT_PREFS.theme,
    themes: up.SLACKIFY_THEMES.THEMES.map((t) => t.id),
  };
  return { css, meta };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { css, meta } = build();
  fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
  fs.writeFileSync(path.join(root, 'dist/user.css'), css);
  fs.writeFileSync(path.join(root, 'src/runtime/upstream-meta.generated.json'), JSON.stringify(meta, null, 2) + '\n');
  console.log(`dist/user.css ${Buffer.byteLength(css)} bytes`);
}
