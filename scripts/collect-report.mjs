// Runs the full verification pipeline and writes docs/TEST_REPORT.md from the REAL results.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sh = (cmd, args) => spawnSync(cmd, args, { cwd: root, encoding: 'utf8', maxBuffer: 1 << 28 });
const ver = (cmd, args) => (sh(cmd, args).stdout || '').trim().split('\n')[0];
const pkgVer = (n) => JSON.parse(fs.readFileSync(path.join(root, 'node_modules', n, 'package.json'), 'utf8')).version;

const steps = [];
function step(name, cmd, parse) {
  const t0 = Date.now();
  const r = sh('npm', ['run', '--silent', cmd]);
  const out = (r.stdout || '') + (r.stderr || '');
  const counts = parse ? parse(out) : null;
  steps.push({ name, cmd: `npm run ${cmd}`, ok: r.status === 0, secs: ((Date.now() - t0) / 1000).toFixed(1), counts, tail: out.split('\n').filter(Boolean).slice(-6).join('\n') });
}
const tap = (out) => {
  const g = (k) => +((new RegExp(`^# ${k} (\\d+)`, 'm').exec(out) || [])[1] || 0);
  return { tests: g('tests'), pass: g('pass'), fail: g('fail'), skipped: g('skipped') + g('todo'), cancelled: g('cancelled') };
};

step('build', 'build');
step('check (syntax, CJS contract, static CSS/tag checks)', 'check', (o) => ({ ok: (o.match(/^ok /gm) || []).length, fail: (o.match(/^FAIL /gm) || []).length }));
step('lint (ESLint)', 'lint');
step('unit', 'test:unit', tap);
step('dom (jsdom)', 'test:dom', tap);
step('visual (Playwright, mock HTML only)', 'test:visual', () => {
  const j = JSON.parse(fs.readFileSync(path.join(root, 'test-results/visual.json'), 'utf8'));
  return { tests: j.stats.expected + j.stats.unexpected + j.stats.skipped + j.stats.flaky, pass: j.stats.expected, fail: j.stats.unexpected, skipped: j.stats.skipped, flaky: j.stats.flaky };
});
step('package (dist/install.sh)', 'package');
step('installer (mock Recipe dirs)', 'test:installer', tap);

const upstream = JSON.parse(fs.readFileSync(path.join(root, 'src/upstream/pins.json'), 'utf8'));
const size = (f) => fs.statSync(path.join(root, f)).size;
const shots = fs.existsSync(path.join(root, 'test/visual/screenshots')) ? fs.readdirSync(path.join(root, 'test/visual/screenshots')).filter((f) => f.endsWith('.png') && !f.startsWith('dump')).sort() : [];
const total = steps.reduce((a, s) => { if (s.counts && s.counts.tests !== undefined) { a.tests += s.counts.tests; a.pass += s.counts.pass; a.fail += s.counts.fail; a.skipped += s.counts.skipped; } return a; }, { tests: 0, pass: 0, fail: 0, skipped: 0 });
const allOk = steps.every((s) => s.ok) && total.fail === 0 && total.skipped === 0;
const fmt = (c) => (c ? (c.tests !== undefined ? `${c.tests} tests: ${c.pass} pass / ${c.fail} fail / ${c.skipped} skipped` : `${c.ok} checks ok / ${c.fail} failed`) : '-');

const md = `# Test report

Generated by \`npm run report\` (which executes the real pipeline below) on ${new Date().toISOString()}.
**Mock DOM only. Nothing here proves compatibility with the real Google Chat or a real Ferdium** - see [LIMITATIONS.md](LIMITATIONS.md).

## Environment

| | |
|---|---|
| OS | ${ver('sw_vers', ['-productName'])} ${ver('sw_vers', ['-productVersion'])} (${os.arch()}, Darwin ${os.release()}) |
| Node / npm | ${process.version} / ${ver('npm', ['-v'])} |
| esbuild / postcss / eslint | ${pkgVer('esbuild')} / ${pkgVer('postcss')} / ${pkgVer('eslint')} |
| jsdom | ${pkgVer('jsdom')} |
| @playwright/test / Chromium | ${pkgVer('@playwright/test')} / headless shell ${(fs.readdirSync(path.join(os.homedir(), 'Library/Caches/ms-playwright')).find((d) => d.startsWith('chromium_headless_shell')) || 'n/a')} |
| bash / zsh | ${ver('/bin/bash', ['--version'])} / ${ver('/bin/zsh', ['--version'])} |

## Upstream commits

${Object.entries(upstream).map(([n, p]) => `* ${n}: \`${p.commit}\` (${p.branch})`).join('\n')}

## Commands run

| Step | Command | Result | Counts | Seconds |
|---|---|---|---|---|
${steps.map((s) => `| ${s.name} | \`${s.cmd}\` | ${s.ok ? 'PASS' : '**FAIL**'} | ${fmt(s.counts)} | ${s.secs} |`).join('\n')}

**Test totals (unit + dom + visual + installer): ${total.tests} tests, ${total.pass} passed, ${total.fail} failed, ${total.skipped} skipped.**

## Artifacts

| File | Bytes |
|---|---|
| dist/user.css | ${size('dist/user.css')} |
| dist/user.js | ${size('dist/user.js')} |
| dist/.fs-runtime.cjs | ${size('dist/.fs-runtime.cjs')} |
| dist/install.sh | ${size('dist/install.sh')} |

## Screenshots (diagnostic only; not used as pass/fail baselines)

Saved to \`test/visual/screenshots/\`: ${shots.length} files.
${shots.map((f) => `* ${f}`).join('\n')}

## Not verified

* Real Ferdium (any version): not launched.
* Real Google Chat DOM: never contacted; every selector heuristic is checked only against the synthetic fixture in \`test/fixtures/chat-fixture.mjs\`.
* Real macOS user profiles: installer tests use temporary \`HOME\` directories with mock Recipe folders.
* Behaviour under Ferdium's Content-Security-Policy handling of the embedded \`data:\` font and the gstatic logo swap.
* Japanese UI strings other than \`今日\`/\`昨日\`/\`<曜日>\` day labels are best-guess (e.g. \`N件の返信\`).
* Performance numbers are budgets, not measurements on a real conversation (the 600-topic mock test only checks laziness and activation time).

## Known issues

${allOk ? 'None found by the automated tests.' : 'See failing steps above.'}

## Completion verdict

${allOk ? '**PASS** - all automated checks passed with 0 failures and 0 skipped tests. This is an implementation-complete verdict against the mock environment, not a production guarantee.' : '**FAIL** - at least one step failed; do not treat the implementation as complete.'}

## Step output tails

${steps.map((s) => `### ${s.name}\n\`\`\`\n${s.tail}\n\`\`\``).join('\n\n')}
`;
fs.writeFileSync(path.join(root, 'docs/TEST_REPORT.md'), md);
console.log(md.split('## Artifacts')[0].split('## Commands run')[1]);
process.exit(allOk ? 0 : 1);
